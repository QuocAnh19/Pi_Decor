-- Backs: quotations created by admin for a lead (quotation number, items array,
--   subtotal, discount, total, status, valid_until, notes).
--   Prompt 09 will add API routes to CRUD quotations.
--   Prompt 16 will build the quotation builder UI & PDF export.
-- ============================================================================

create table if not exists quotations (
  id                uuid primary key default gen_random_uuid(),
  lead_id           uuid not null references leads(id) on delete cascade,
  admin_id          uuid references admins(id) on delete set null,
  quotation_number  text not null unique,   -- e.g. "BG-2026-0001" generated in app-code
  items             jsonb not null default '[]',
  -- items: [{ description, quantity, unit_price, subtotal }]
  subtotal          integer not null default 0,  -- VND (integer to avoid node-postgres numeric string conversion)
  discount          integer not null default 0,
  total             integer not null default 0,
  status            text not null default 'draft'
                     check (status in ('draft','sent','accepted','declined','expired')),
  valid_until       date,
  notes             text,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

comment on table quotations is
  'Quotation records generated by admin for leads.';

create index if not exists idx_quotations_lead_id on quotations (lead_id, created_at desc);

drop trigger if exists trg_quotations_updated_at on quotations;
create trigger trg_quotations_updated_at
  before update on quotations
  for each row execute function set_updated_at();
